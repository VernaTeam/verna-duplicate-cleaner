def t(lang: str, key: str, **kw) -> str:
    """Look a key up, falling back to Persian and then to the key itself."""
    table = STRINGS.get(lang) or STRINGS[DEFAULT_LANG]
    text = table.get(key)
    if text is None:
        text = STRINGS[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            return text.format(**kw)
        except (KeyError, IndexError):
            return text
    return text


def check_parity() -> list[str]:
    """Keys present in one language but not the other. Used by the self-test."""
    fa, en = set(STRINGS["fa"]), set(STRINGS["en"])
    return sorted(("fa-only: " + k for k in fa - en)) + \
           sorted(("en-only: " + k for k in en - fa))


